export function shuffleCards(cards = [], random = Math.random) {
  const result = Array.isArray(cards) ? [...cards] : [];

  for (let index = result.length - 1; index > 0; index -= 1) {
    const randomIndex = Math.floor(random() * (index + 1));

    [result[index], result[randomIndex]] = [
      result[randomIndex],
      result[index],
    ];
  }

  return result;
}

export function getRandomCard(options = {}) {
  const {
    color = null,
    type = null,
    baggedOnly = false,
    excludeIds = [],
    random = Math.random,
  } = options;

  const excludedIdSet = new Set(
    Array.isArray(excludeIds) ? excludeIds : []
  );

  const source = baggedOnly ? baggedCards : dccsClothingCards;

  const candidates = source.filter((card) => {
    if (color && card.color !== color) return false;
    if (type && card.type !== type) return false;
    if (excludedIdSet.has(card.id)) return false;

    return true;
  });

  if (candidates.length === 0) return null;

  const randomIndex = Math.floor(random() * candidates.length);

  return candidates[randomIndex];
}

