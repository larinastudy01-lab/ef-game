function createClothingCard({
  id,
  color,
  type,
  normalImg,
  bagImg = null,
}) {
  if (!id || !color || !type || !normalImg) {
    throw new Error(`DCCS clothing card 資料不完整：${id || "unknown"}`);
  }

  return Object.freeze({
    id,
    color,
    type,

    colorText: colorLabels[color] || color,
    typeText: typeLabels[type] || type,

    // 保留 img，讓舊版 TestPage_DCCS.jsx 仍可使用 card.img。
    img: normalImg,

    normalImg,
    bagImg,
    hasBagImage: Boolean(bagImg),

    normalAlt: `${colorLabels[color] || color}${typeLabels[type] || type}`,
    bagAlt: `${colorLabels[color] || color}${
      typeLabels[type] || type
    }，已裝入透明塑膠袋`,
  });
}

