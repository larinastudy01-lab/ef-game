export function getCard(cardId) {
  if (!cardId) return null;

  return (
    dccsClothingCards.find((card) => card.id === String(cardId)) ||
    null
  );
}

export function getCardsByColor(color, options = {}) {
  const { baggedOnly = false } = options;

  if (!DCCS_COLORS.includes(color)) return [];

  const source = baggedOnly ? baggedCards : dccsClothingCards;

  return source.filter((card) => card.color === color);
}

